def main(only) -> int:
    missed = 0
    chosen = [m for m in MUTATIONS if not only or any(o in m[0] for o in only)]
    with tempfile.TemporaryDirectory() as tmp:
        for name, fname, old, new, expect in chosen:
            work = pathlib.Path(tmp) / "w"
            shutil.rmtree(work, ignore_errors=True)
            shutil.copytree(
                ROOT, work, ignore=shutil.ignore_patterns(".git", "__pycache__", ".gpubox")
            )
            path = work / "src/gpubox" / fname
            text = path.read_text()
            if text.count(old) != 1:
                print(f"STALE   {name}: text found {text.count(old)} times")
                missed += 1
                continue
            path.write_text(text.replace(old, new))
            r = subprocess.run(
                [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"],
                cwd=work, capture_output=True, text=True, timeout=600,
            )  # fmt: skip
            failed = [
                line[7:].split(" ")[0]
                for line in r.stdout.splitlines()
                if line.startswith("FAILED")
            ]
            hit = [t for t in failed if expect in t]
            if r.returncode == 1 and hit:
                print(f"caught  {name}  <- {hit[0].split('::')[-1][:60]} (+{len(failed) - 1} more)")
            else:
                why = f"suite exit {r.returncode}, {len(failed)} failed, none named *{expect}*"
                print(
                    f"MISSED  {name}: {why}; failed: {[t.split('::')[-1][:40] for t in failed[:3]]}"
                )
                missed += 1
    print(f"{len(chosen) - missed} of {len(chosen)} caught")
    return 1 if missed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
